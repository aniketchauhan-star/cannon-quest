// Writes src/15_vodata.js (run by build.sh): the voice lines that have a clip of a real person's voice.
// A clip counts only when tools/vo_split.py cut it from a recording and wrote the cut down in tools/vo_takes.json.
// Any other clip in assets/VO/en/ (not known to be a real voice) is left out, with a warning.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const at = (p) => path.join(ROOT, p);
const takes = fs.existsSync(at('tools/vo_takes.json')) ? JSON.parse(fs.readFileSync(at('tools/vo_takes.json'), 'utf8')) : {};
const dir = 'assets/VO/en/';
const have = fs.existsSync(at(dir)) ? fs.readdirSync(at(dir)).filter((f) => f.endsWith('.webm')).map((f) => f.slice(0, -5)) : [];
for (const k of have.filter((k) => !takes[k]))
  console.error(`warning: ${dir}${k}.webm was not cut from a recording (not in tools/vo_takes.json), so the game leaves it out`);
const keys = have.filter((k) => takes[k]).sort();
const words = Object.fromEntries(keys.filter((k) => Array.isArray(takes[k].words)).map((k) => [k, takes[k].words]));
fs.writeFileSync(at('src/15_vodata.js'),
  "// generated by build.sh (tools/vo_data.mjs) from tools/vo_takes.json: the lines voiced by a real person's recording\n" +
  `const VO_FILES = ${JSON.stringify(keys)}; // keys with a clip in assets/VO/en/ (the other lines are not voiced)\n` +
  `const VO_WORDS = ${JSON.stringify(words)}; // when each word of a clip starts (s from the clip's start), for the board\n`);
console.log(`voice: ${keys.length} recorded clip(s)`);
