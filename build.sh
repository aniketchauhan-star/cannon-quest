#!/bin/sh
# Builds the game from src/ (see README.md):
#   locales/locales.js  the words, for file:// (from locales/locales.json, which is checked)
#   js/script.js        the game (src/*.js, with the sound effects embedded so it works offline / from file://)
#   js/loader.js        the loading screen (src/05_loader.js + the size of every file it waits for)
#   index.html          the page and its styles (src/00_head.html + src/99_tail.html), which loads
#                       libs/gsap.min.js, js/loader.js, js/i18n.js, the words, then js/script.js
cd "$(dirname "$0")" || exit 1
node tools/gen_locales.mjs || exit 1
{
  echo "// generated by build.sh from assets/sfx/*.webm (real recorded sound effects, Opus; see CREDITS.md)"
  echo "const SFX_DATA = {"
  for f in assets/sfx/*.webm; do printf "  '%s': '%s',\n" "$(basename "$f" .webm)" "$(base64 < "$f" | tr -d '\n')"; done
  echo "};"
  printf "const VO_FILES = [%s]; // keys with a clip in assets/VO/en/ (Aamir's studio); the other lines use the device's voice\n" \
    "$(for f in assets/VO/en/*.webm; do [ -e "$f" ] && printf "'%s'," "$(basename "$f" .webm)"; done)"
  printf "const VO_MOOD = %s; // each line's mood (tools/vo_lines.json), which colours the device's voice\n" \
    "$(node -e 'process.stdout.write(JSON.stringify(require("./tools/vo_lines.json").mood || {}))')"
} > src/15_sfxdata.js
cat src/10_core.js src/12_motion.js src/15_sfxdata.js src/20_audio.js src/30_stage.js src/35_title.js src/40_game.js > js/script.js
# js/loader.js: the loading screen (src/05_loader.js), after the byte size of every image and of the game script,
# so its bar fills by bytes
{
  echo "// generated by build.sh: every image's size in bytes, the game script's, then src/05_loader.js"
  printf "var IMG_BYTES = {"
  for f in assets/img/*; do [ -f "$f" ] && printf "'%s':%s," "$(basename "$f")" "$(wc -c < "$f" | tr -d ' ')"; done
  echo "};"
  printf "var LOAD_SCRIPT = ['js/script.js', %s];\n" "$(wc -c < js/script.js | tr -d ' ')"
  cat src/05_loader.js
} > js/loader.js
cat src/00_head.html src/99_tail.html > index.html
echo "Built index.html ($(wc -c < index.html | tr -d ' ') bytes) + js/script.js ($(wc -c < js/script.js | tr -d ' ') bytes)"
