#!/bin/sh
# Builds the game from src/ (see README.md):
#   locales/locales.js  the words, for file:// (from locales/locales.json, which is checked)
#   js/script.js        the game (src/*.js)
#   js/sfx_title.js     the start screen's own sound effects (its entrance), embedded and small: loaded with the
#                       page, so they are ready when the title, the cannon and the cage arrive
#   js/sfx.js           every other sound effect, embedded (so they work offline / from file://). The game fetches
#                       this once the start screen is up, so it never holds up the first screen
#   index.html          the page and its styles (src/00_head.html + src/99_tail.html), which loads
#                       libs/gsap.min.js, js/i18n.js, js/sfx_title.js, the words, then js/script.js. There is no loading screen
cd "$(dirname "$0")" || exit 1
node tools/gen_locales.mjs || exit 1
# the start screen's entrance sounds (Title.cues in src/35_title.js; real recordings, see CREDITS.md)
TITLE_SFX="swish knock thud clang roll cork"
sfxjs() { # sfxjs <file> <what it is> <clip>…: the clips as base64, added to SFX_DATA (Sound.loadSfx decodes each once)
  out=$1; what=$2; shift 2
  {
    echo "// generated by build.sh from assets/sfx/*.webm (real recorded sound effects, Opus; see CREDITS.md)."
    echo "// $what"
    echo "var SFX_DATA = Object.assign(window.SFX_DATA || {}, {"
    for k in "$@"; do printf "  '%s': '%s',\n" "$k" "$(base64 < "assets/sfx/$k.webm" | tr -d '\n')"; done
    echo "});"
    echo "if (typeof Sound !== 'undefined') Sound.loadSfx();"
  } > "$out"
}
for k in $TITLE_SFX; do [ -f "assets/sfx/$k.webm" ] || { echo "missing assets/sfx/$k.webm"; exit 1; }; done
REST=""
for f in assets/sfx/*.webm; do k=$(basename "$f" .webm); case " $TITLE_SFX " in *" $k "*) ;; *) REST="$REST $k" ;; esac; done
# (the clip lists are split into words on purpose)
sfxjs js/sfx_title.js "The start screen's entrance sounds: the page loads this with itself (src/99_tail.html)." $TITLE_SFX
sfxjs js/sfx.js "boot() (src/40_game.js) fetches this once the start screen is up." $REST
# the voice: only clips cut from a person's recording by tools/vo_split.py (written down in tools/vo_takes.json)
node tools/vo_data.mjs || exit 1
cat src/10_core.js src/12_motion.js src/15_vodata.js src/20_audio.js src/30_stage.js src/32_scenery.js src/35_title.js src/40_game.js > js/script.js
# index.html: the page, with its fonts (Trig Text for the equation and the orbs' numbers, below), Poppins SemiBold (600; SIL OFL 1.1, assets/fonts/OFL-Poppins.txt),
# embedded where src/00_head.html says <!--FONTS--> (a data: URI, so it also loads from file://, which blocks font files)
{
  echo "<style>/* generated by build.sh from assets/fonts/poppins-600-*.woff2, poppins-700-*.woff2, swifty-math.woff2 + trigtext-regular.woff2 */"
  printf "@font-face{font-family:'Poppins';font-style:normal;font-weight:600;font-display:block;src:url(data:font/woff2;base64,%s) format('woff2');unicode-range:U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+2074,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD}\n" \
    "$(base64 < assets/fonts/poppins-600-latin.woff2 | tr -d '\n')"
  printf "@font-face{font-family:'Poppins';font-style:normal;font-weight:600;font-display:block;src:url(data:font/woff2;base64,%s) format('woff2');unicode-range:U+0100-02AF,U+0304,U+0308,U+0329,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF}\n" \
    "$(base64 < assets/fonts/poppins-600-latin-ext.woff2 | tr -d '\n')"
  # the equation on the cloud and the question board's words: Poppins Bold (700), as in the user's Distance Formula
  # game (the user, 26 Nov 2026: "use Poppins, like distance formula"); Google's own files, same licence
  printf "@font-face{font-family:'Poppins';font-style:normal;font-weight:700;font-display:block;src:url(data:font/woff2;base64,%s) format('woff2');unicode-range:U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD}\n" \
    "$(base64 < assets/fonts/poppins-700-latin.woff2 | tr -d '\n')"
  printf "@font-face{font-family:'Poppins';font-style:normal;font-weight:700;font-display:block;src:url(data:font/woff2;base64,%s) format('woff2');unicode-range:U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF}\n" \
    "$(base64 < assets/fonts/poppins-700-latin-ext.woff2 | tr -d '\n')"
  # …and its x set as mathematics, the way Distance Formula sets it: Latin Modern Math's italic x (TeX's own), renamed
  # Swifty Math as its licence asks (assets/fonts/GUST-FONT-LICENSE.txt); the file is Distance Formula's (d, x, y, ₀–₉)
  printf "@font-face{font-family:'Swifty Math';font-style:italic;font-weight:400;font-display:block;src:url(data:font/woff2;base64,%s) format('woff2');unicode-range:U+0064,U+0078-0079,U+2080-2089}\n" \
    "$(base64 < assets/fonts/swifty-math.woff2 | tr -d '\n')"
  # the numbers on the orbs (and the end title): Trig Text (400; SIL OFL 1.1, assets/fonts/OFL-TrigText.txt)
  printf "@font-face{font-family:'Trig Text';font-style:normal;font-weight:400;font-display:block;src:url(data:font/woff2;base64,%s) format('woff2')}\n" \
    "$(base64 < assets/fonts/trigtext-regular.woff2 | tr -d '\n')"
  echo "</style>"
} > src/02_fonts.html
{ sed '/<!--FONTS-->/,$d' src/00_head.html; cat src/02_fonts.html; sed '1,/<!--FONTS-->/d' src/00_head.html; cat src/99_tail.html; } > index.html
grep -q '<!--FONTS-->' src/00_head.html || echo "warning: no <!--FONTS--> line in src/00_head.html, so the font is not embedded"
echo "Built index.html ($(wc -c < index.html | tr -d ' ') bytes) + js/script.js ($(wc -c < js/script.js | tr -d ' ') bytes) + js/sfx_title.js ($(wc -c < js/sfx_title.js | tr -d ' ') bytes) + js/sfx.js ($(wc -c < js/sfx.js | tr -d ' ') bytes)"
